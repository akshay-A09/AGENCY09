<script>
    document.addEventListener("DOMContentLoaded", function () {
    const exploreBtn = document.querySelector(".explore-btn"); // Update selector based on your nav trigger button class/id
    const menuRow = document.querySelector(".menu_row");
    const closeBtn = document.querySelector(".menuBtn.Open a");

    if (exploreBtn && menuRow) {
        exploreBtn.addEventListener("click", function (e) {
            e.preventDefault();
            menuRow.classList.add("Show");
        });
    }

    if (closeBtn && menuRow) {
        closeBtn.addEventListener("click", function (e) {
            e.preventDefault();
            menuRow.classList.remove("Show");
        });
    }
});
    </script>

<script>
    document.addEventListener("DOMContentLoaded", function () {
    const buttons = document.querySelectorAll(".addressTab-btn");
    const panels = document.querySelectorAll(".addressTab-panel");

    buttons.forEach(button => {
        button.addEventListener("click", () => {
            const targetId = button.getAttribute("data-target");

            buttons.forEach(btn => btn.classList.remove("active"));
            panels.forEach(panel => panel.classList.remove("active"));

            button.classList.add("active");
            document.getElementById(targetId).classList.add("active");
        });
    });
});
</script>

