<script>
document.addEventListener("DOMContentLoaded", function () {
    // 1. Get all clock elements on the page automatically
    const clocks = document.querySelectorAll(".an_clock");

    // 2. Helper function to get the current time for a specific timezone
    function getTime(timezone) {
        let time = new Date().toLocaleTimeString("en-US", {
            hour12: false,
            hour: '2-digit',
            minute: '2-digit',
            second: '2-digit',
            timeZone: timezone
        });
        return time.split(":");
    }

    // 3. Loop through each clock and set up its drawing interval
    clocks.forEach(canvas => {
        const ctx = canvas.getContext("2d");
        const timezone = canvas.getAttribute("data-timezone"); // Reads timezone from your HTML
        const radius = canvas.height / 2;
        const clockRadius = radius * 0.90;

        setInterval(() => {
            // Clear the canvas completely for the new frame
            ctx.save();
            ctx.setTransform(1, 0, 0, 1, 0, 0);
            ctx.clearRect(0, 0, canvas.width, canvas.height);
            ctx.restore();

            // Move the center point for drawing
            ctx.save();
            ctx.translate(radius, radius);

            drawFace(ctx, clockRadius);
            drawTime(ctx, clockRadius, timezone); // Numbers are removed to keep it plain

            ctx.restore();
        }, 1000);
    });

    // 4. Drawing Functions
    function drawFace(ctx, radius) {
        var grad;
        ctx.beginPath();
        ctx.arc(0, 0, radius, 0, 2 * Math.PI);
        ctx.fillStyle = '#fff';
        ctx.fill();
        
        grad = ctx.createRadialGradient(0, 0, radius * 0.95, 0, 0, radius * 1.05);
        grad.addColorStop(0, '#006dea');
        grad.addColorStop(0.5, '#006dea');
        grad.addColorStop(1, '#006dea');
        ctx.strokeStyle = grad;
        ctx.lineWidth = radius * 0.0;
        ctx.stroke();
        
        ctx.beginPath();
        ctx.arc(0, 0, radius * 0.1, 0, 2 * Math.PI);
        ctx.fillStyle = '#006dea'; // Blue center dot
        ctx.fill();
    }

    function drawTime(ctx, radius, timezone) {
        var time = getTime(timezone);
        var hour = parseInt(time[0], 10);
        var minute = parseInt(time[1], 10);
        var second = parseInt(time[2], 10);
        
        // Hour Hand
        hour = hour % 12;
        hour = (hour * Math.PI / 6) + (minute * Math.PI / (6 * 60)) + (second * Math.PI / (360 * 60));
        drawHand(ctx, hour, radius * 0.5, radius * 0.08, '#006dea'); // Black
        
        // Minute Hand
        minute = (minute * Math.PI / 30) + (second * Math.PI / (30 * 60));
        drawHand(ctx, minute, radius * 0.8, radius * 0.06, '#006dea'); // Black
        
        // Second Hand
        second = (second * Math.PI / 30);
        drawHand(ctx, second, radius * 0.9, radius * 0.03, '#006dea'); // Blue
    }

    function drawHand(ctx, pos, length, width, color) {
        ctx.beginPath();
        ctx.lineWidth = width;
        ctx.lineCap = "round";
        ctx.strokeStyle = color;
        ctx.moveTo(0, 0);
        ctx.rotate(pos);
        ctx.lineTo(0, -length);
        ctx.stroke();
        ctx.rotate(-pos);
    }
});

